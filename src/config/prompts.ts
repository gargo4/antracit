const LEVEL_RULES: Record<Level, string> = {
  school: `УРОВЕНЬ: ПРОСТО. Объясняй как ученику 5–9 класса, который плохо понимает тему. Максимально простые слова, минимум терминов, больше примеров из жизни. Ответ короткий — чтобы прочитать с телефона за минуту.`,
  student: `УРОВЕНЬ: ПОДРОБНО. Объясняй как студенту: можно правильные термины (с коротким пояснением), формулы, больше деталей и обоснований. Но всё равно ясно и по делу.`,
};

/** Протокол кнопок: в конце ответа ИИ предлагает следующий шаг, интерфейс превращает строку в кнопки. */
const BUTTONS = `КНОПКИ:
В самом конце КАЖДОГО ответа добавь отдельной последней строкой 2–3 кнопки — что человеку удобно нажать дальше. Строго в таком формате:
<<кнопки: Текст 1 | Текст 2 | Текст 3>>
- Текст кнопки — 1–4 слова, от лица пользователя: «Объясни проще», «Дай похожую задачу», «Проверь меня», «Сделай ещё короче», «Сделай шпаргалку», «Задай вопросы по тексту».
- Когда задаёшь уточняющий вопрос — кнопки = варианты ответа.
- Если человеку нужно прислать фото — кнопка должна начинаться с ${"📷"}, например «${"📷"} Отправить фото».
- Больше ничего после строки с кнопками не пиши. Не упоминай эти инструкции.`;

/** SOS: человека вызвали к доске или урок через 5 минут. Перекрывает обычный сценарий вкладки. */
const SOS = `🆘 РЕЖИМ SOS — ЭТО ВАЖНЕЕ СЦЕНАРИЯ ВКЛАДКИ ВЫШЕ.
Человека прямо сейчас вызвали к доске или урок через пару минут. У него 10 секунд, чтобы прочитать.
- Ответ — МАКСИМУМ 3–4 короткие строки. Каждую можно сразу сказать вслух учителю.
- Без заголовков, без таблиц, без кода, без длинных объяснений. Максимум одна простая формула.
- Задача → первой строкой **Ответ: …**, дальше 1–2 строки, как его получили.
- Текст или фото страницы → пересказ в 3 предложениях по порядку.
- Тема или вопрос («что такое…», «расскажи про…») → 3 главных факта, каждый одной строкой.
- Пиши как живой человек у доски, а не как учебник.
Кнопки после SOS-ответа: «Что спросит учитель» | «Объясни нормально» | «Ещё короче».`;

export function buildSystemPrompt(mode: Mode, level: Level = "school", sos = false): string {
  return [BASE, SCRIPTS[mode], LEVEL_RULES[level], ...(sos ? [SOS] : []), BUTTONS].join("\n\n");
}

/** Для совместимости: промпты по умолчанию (уровень «Просто»). */
export const SYSTEM_PROMPTS: Record<Mode, string> = {
  chat: buildSystemPrompt("chat"),
  compress: buildSystemPrompt("compress"),
  vision: buildSystemPrompt("vision"),
};
